/*
  TIMBER TERROR
*/
export function getTimberTerrorImage(skin: UniqueImageSkin | null) {
  switch (skin) {
    case `shadow_self`:
      return require("../../assets/images/heroes/timber_terror/shadow_timber_terror.webp");
    case `ascended_self`:
      return require("../../assets/images/heroes/timber_terror/ascended_timber_terror.webp");
    case `gale_force`:
      return require("../../assets/images/heroes/timber_terror/gale_force_timber_terror.webp");
    case `fire_brand`:
      return require("../../assets/images/heroes/timber_terror/fire_brand_timber_terror.webp");
    case `earth_shaker`:
      return require("../../assets/images/heroes/timber_terror/earth_shaker_timber_terror.webp");
    case `tide_caller`:
      return require("../../assets/images/heroes/timber_terror/tide_caller_timber_terror.webp");
    default:
      return require("../../assets/images/heroes/timber_terror/timber_terror.webp");
  }
}

